"""
Builds the NJ.TATTOO logotype as SVG paths from Archivo (SIL OFL 1.1 — modified outlines
are permitted; the result is a logo, not a font, so no Reserved Font Name is involved).

  NJ   — N and J cut at width 125 / weight 900, re-spaced by eye, full stop replaced by a true circle
  TATTOO — width 62 / weight 200, kerned by HarfBuzz from the font's own GPOS table

Both pieces also exist in the inverted state (condensed-light NJ, wide-black TATTOO) for the footer.
Run (needs fonttools, brotli, uharfbuzz):  python scripts/build-marks.py
Writes: src/components/marks/paths.ts
"""
import io
import json
import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

SRC = "src/fonts/Archivo-latin.woff2"
CAP = 688  # cap height incl. overshoot; the SVG's y=0 is the cap line, y=CAP the baseline


def fmt(v):
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def instance(wght, wdth):
    f = TTFont(SRC)
    return instancer.instantiateVariableFont(f, {"wght": wght, "wdth": wdth})


def shape(font, text, track=0):
    buf = io.BytesIO()
    font.flavor = None  # HarfBuzz wants plain sfnt, not woff2
    font.save(buf)
    face = hb.Face(buf.getvalue())
    hbfont = hb.Font(face)
    b = hb.Buffer()
    b.add_str(text)
    b.guess_segment_properties()
    hb.shape(hbfont, b, {"kern": True, "liga": False})
    order = font.getGlyphOrder()
    x = 0
    out = []
    for info, pos in zip(b.glyph_infos, b.glyph_positions):
        out.append((order[info.codepoint], x + pos.x_offset))
        x += pos.x_advance + track
    return out


def build(text, wght, wdth, track=0, adjust=None):
    """Returns (path_d, xmin, xmax, per-glyph list). `adjust` maps glyph index -> extra x shift."""
    font = instance(wght, wdth)
    gs = font.getGlyphSet()
    placed = shape(font, text, track)
    pen = SVGPathPen(gs, ntos=fmt)
    bounds = BoundsPen(gs)
    parts = []
    xmin, xmax = 1e9, -1e9
    for i, (name, x) in enumerate(placed):
        dx = x + (adjust.get(i, 0) if adjust else 0)
        # glyph y-up -> svg y-down, baseline at y=CAP
        t = (1, 0, 0, -1, dx, CAP)
        p = SVGPathPen(gs, ntos=fmt)
        gs[name].draw(TransformPen(p, t))
        b = BoundsPen(gs)
        gs[name].draw(TransformPen(b, t))
        parts.append({"d": p.getCommands(), "bounds": b.bounds})
        xmin = min(xmin, b.bounds[0])
        xmax = max(xmax, b.bounds[2])
    return parts, xmin, xmax


def shift(d_parts, xmin):
    """Re-bases x so the leftmost ink sits at 0 (optical left alignment) by wrapping in a translate."""
    return -xmin


def wordmark(text, wght, wdth, track=0, adjust=None):
    parts, xmin, xmax = build(text, wght, wdth, track, adjust)
    top = min(p["bounds"][1] for p in parts)
    bottom = max(p["bounds"][3] for p in parts)
    return {
        "paths": [p["d"] for p in parts],
        "x": round(-xmin, 1),  # translate so ink starts at 0
        "width": round(xmax - xmin, 1),
        "top": round(top, 1),
        "bottom": round(bottom, 1),
    }


def nj(wght, wdth, gap_adjust, dot_d, dot_gap, track=0):
    # glyph 1 (J) is nudged by gap_adjust to tighten the N–J pair by eye
    w = wordmark("NJ", wght, wdth, track, {1: gap_adjust})
    r = dot_d / 2
    right = w["width"]  # ink right edge, after the x re-basing
    cx = right + dot_gap + r
    cy = CAP + 12 - r  # round forms overshoot the baseline by 12 units, like the J
    return {**w, "dot": {"cx": round(cx, 1), "cy": round(cy, 1), "r": r}, "total": round(cx + r, 1)}


out = {
    "cap": CAP,
    "njWide": nj(900, 125, gap_adjust=-34, dot_d=226, dot_gap=70),
    "njCond": nj(200, 62, gap_adjust=-4, dot_d=86, dot_gap=34, track=6),
    "tattooCond": wordmark("TATTOO", 200, 62, track=10),
    "tattooWide": wordmark("TATTOO", 900, 125, track=-20),
}

ts = "// Generated by scripts/build-marks.py from Archivo (SIL OFL 1.1). Do not edit by hand.\n"
ts += "export const marks = " + json.dumps(out, indent=2) + " as const;\n"
import os

os.makedirs("src/components/marks", exist_ok=True)
with open("src/components/marks/paths.ts", "w", encoding="utf-8") as fh:
    fh.write(ts)
for k, v in out.items():
    if k != "cap":
        print(k, "width", v["width"], "top", v["top"], "bottom", v["bottom"], v.get("dot", ""), v.get("total", ""))
nj = out["njWide"]
tt = out["tattooCond"]
print("--- CSS constants (Header.module.css, Intro.module.css) ---")
print("NJ aspect  total/700 =", round(nj["total"], 1), "/ 700")
print("ink ratio (ink / total) =", round(nj["width"] / nj["total"], 4))
print("TATTOO cond width =", tt["width"])
